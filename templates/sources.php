<h1 class="h3">Data sources and licences</h1>

<p>
  Ethical Buy combines open data with our own research. This page lists where
  each part comes from and the licence it is used under.
</p>

<h2 class="h5 mt-4">Open Food Facts</h2>
<p>
  Product names, categories, labels, Nutri-Score and Eco-Score grades, and the
  link between products and brands come from
  <a href="https://world.openfoodfacts.org" rel="noopener noreferrer">Open Food Facts</a>,
  a free, collaborative database of food products.
</p>
<p>
  Contains data from Open Food Facts, available under the
  <a href="https://opendatacommons.org/licenses/odbl/1-0/" rel="noopener noreferrer">Open Database License (ODbL) 1.0</a>.
  Individual contents of the database are available under the
  <a href="https://opendatacommons.org/licenses/dbcl/1-0/" rel="noopener noreferrer">Database Contents License (DbCL) 1.0</a>.
</p>
<p>
  Product photos are by Open Food Facts contributors, licensed under
  <a href="https://creativecommons.org/licenses/by-sa/4.0/" rel="noopener noreferrer">Creative Commons Attribution-ShareAlike 4.0 (CC BY-SA 4.0)</a>.
  Each product page links to the product on Open Food Facts, where the
  photo's contributors are credited. A brand's photo is the photo of its most
  scanned product.
</p>
<p>
  Photos are loaded directly from Open Food Facts' image servers, not copied to
  ours, so Open Food Facts sees your IP address and browser details when a page
  with a photo is shown. See our <a href="/privacy.php">privacy policy</a>.
</p>

<h2 class="h5 mt-4">Companies House</h2>
<p>
  Where a brand's owner has been matched to a registered UK company, the
  company name, number, status and any person with significant control come
  from the <a href="https://find-and-update.company-information.service.gov.uk/" rel="noopener noreferrer">Companies House register</a>.
  Contains public sector information licensed under the
  <a href="https://www.nationalarchives.gov.uk/doc/open-government-licence/version/3/" rel="noopener noreferrer">Open Government Licence v3.0</a>.
</p>

<h2 class="h5 mt-4">Our own work</h2>
<p>
  The scores, the overall ratings, the notes on each brand and the ownership
  type recorded for each brand are our own. The ownership types were compiled
  by hand from public information and have not been independently verified.
  How each score is worked out is described in
  <a href="/about.php#how-scores-work">how scores work</a>. If you find a mistake,
  see <a href="/corrections.php">corrections</a>.
</p>
