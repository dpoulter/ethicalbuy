<h1 class="h3">Corrections</h1>

<p class="lead">
  If something on Ethical Buy is wrong, we want to fix it.
</p>

<p>
  This applies whether you are a reader who has spotted a mistake or you
  represent a brand or company we describe. Ownership in particular changes
  often, and our record of each brand's ownership type was compiled by hand
  and has not been independently verified, so reports are genuinely useful.
</p>

<h2 class="h5 mt-4">How to report a problem</h2>
<ul>
  <li>
    On any brand or product page, use the <strong>Report a problem</strong> link.
    It opens the <a href="/contact.php">contact form</a> with the brand or product
    already filled in.
  </li>
  <li>Or email <?= legal_email_link() ?>.</li>
</ul>
<p>
  Tell us what is wrong and, if you can, where the correct information can be
  checked: a company filing, an annual report, a product label or a
  published statement. Evidence we can check ourselves is what lets us act
  quickly.
</p>

<h2 class="h5 mt-4">What we will do</h2>
<ul>
  <li>We aim to acknowledge every report within 5 working days.</li>
  <li>
    We will check what you have told us against the evidence. Where
    information is demonstrably wrong we will correct it or remove it,
    normally within 10 working days of confirming the error.
  </li>
  <li>
    Where the data comes from Open Food Facts, we will also explain how to
    correct it there, so the fix reaches everyone who uses it.
  </li>
  <li>We will tell you what we have done and why.</li>
</ul>
<p>
  Scores and ratings reflect our published method and our own judgement. We
  will always correct the facts a score is built on, but disagreement with the
  method alone is not an error. We still welcome it, and it may shape how the
  method changes.
</p>
</div>
